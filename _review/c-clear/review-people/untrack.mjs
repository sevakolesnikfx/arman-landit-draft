console.log('after one tap on Tracking:', await st(), '| toast:', await page.locator('#toast').innerText(), '| undo button in toast:', await page.locator('#toast button').count());
await btn.click();
await page.waitForTimeout(150);
console.log('after tapping Track again:', await st());
await page.goto(BASE + '?demo=1#/benefit/council-tax-student', { waitUntil: 'load' });
await page.waitForTimeout(300);
console.log('apply btn y / docH / vh:', await page.evaluate(() => { const a = document.querySelector('.apply-wrap a'); return [Math.round(a.getBoundingClientRect().top + scrollY), document.documentElement.scrollHeight, innerHeight]; }));
