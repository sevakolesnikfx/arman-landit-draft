import { pathToFileURL } from 'node:url';
import { createRequire } from 'module';
const require = createRequire('/Users/armanbayatmaku/Desktop/kasdena/websites/landit/package.json');
const { chromium } = require('playwright');
const BASE = pathToFileURL('/Users/armanbayatmaku/Desktop/landit-test/c-clear/index.html').href;
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' });
const page = await ctx.newPage();
await page.goto(BASE + '?demo=1#/chat', { waitUntil: 'load' });
await page.fill('#chat-input', 'railcard'); await page.keyboard.press('Enter'); await page.waitForSelector('.msg-bot');
await page.goto(BASE + '#/settings', { waitUntil: 'load' });
await page.click('[data-action="sign-out"]');
await page.waitForFunction(() => location.hash === '#/login');
await page.click('.auth-tabs a[href="#/register"]');
await page.waitForSelector('#f-name');
await page.fill('#f-name', 'Ben'); await page.fill('#f-email', 'ben@example.com'); await page.fill('#f-pass', 'x');
await page.click('#auth-form button[type=submit]');
await page.waitForFunction(() => /questions/.test(location.hash));
await page.waitForTimeout(200);
const pre = await page.evaluate(() => { const c = document.querySelector('input[name=answer]:checked'); return c && c.value; });
console.log('Q1 preselected for new account:', pre);
await page.click('[data-action="q-skip-all"]');
await page.waitForFunction(() => location.hash === '#/ack');
await page.click('[data-action="ack"]');
await page.waitForFunction(() => location.hash === '#/chat');
await page.waitForTimeout(200);
const st = await page.evaluate(() => JSON.parse(localStorage.getItem('landit-c:state')));
console.log('new account Ben inherits: tracked', st.tracked.map(t => t.id), 'chat msgs', st.chat.length, 'profile', st.profile);
console.log('visible apps in sidebar:', await page.locator('.app-item').count(), 'chat bubbles:', await page.locator('.msg').count());
await browser.close();
