import { pathToFileURL } from 'node:url';
import { createRequire } from 'module';
const require = createRequire('/Users/armanbayatmaku/Desktop/kasdena/websites/landit/package.json');
const { chromium } = require('playwright');
const BASE = pathToFileURL('/Users/armanbayatmaku/Desktop/landit-test/c-clear/index.html').href;
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await ctx.newPage();
await page.goto(BASE + '?demo=1#/benefit/council-tax-student', { waitUntil: 'load' });
await page.waitForTimeout(200);
await page.locator('a', { hasText: /Read 1 post/ }).click();
await page.waitForTimeout(200);
console.log('after Read post:', await page.evaluate(() => location.hash), await page.locator('.posts .post').count());
await page.locator('.side-nav a', { hasText: 'Chat' }).click();
await page.waitForTimeout(200);
await page.locator('.side-nav a', { hasText: 'Community' }).click();
await page.waitForTimeout(200);
console.log('Community tab later:', await page.evaluate(() => location.hash), 'posts shown', await page.locator('.posts .post').count(), 'filter', await page.inputValue('#comm-filter'));
await page.reload(); 
await page.goto(BASE + '#/community', { waitUntil: 'load' });
await page.waitForTimeout(200);
console.log('after reload:', await page.locator('.posts .post').count());
await browser.close();
