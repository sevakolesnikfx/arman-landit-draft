/* Compare every detail panel with LANDIT.benefits. Read-only. */
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
import { createRequire } from 'module';
import { findBanned, DASHES } from '../../../tools/content-rules.mjs';
const require = createRequire('/Users/armanbayatmaku/Desktop/kasdena/websites/landit/package.json');
const { chromium } = require('playwright');
const PAGE = pathToFileURL('/Users/armanbayatmaku/Desktop/landit-test/b-dusk/index.html').href;
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await ctx.newPage();
const errs = [];
page.on('pageerror', e => errs.push(e.message));
await page.goto(PAGE + '?demo=1#/benefits', { waitUntil: 'networkidle' });
await page.waitForTimeout(300);
const ids = await page.evaluate(() => window.LANDIT.benefits.map(b => b.id));
const problems = [];
const samples = {};
for (const id of ids) {
  await page.evaluate(h => { location.hash = h; }, '#/benefit/' + id);
  await page.waitForFunction(h => window.DUSK.lastHash === h && document.getElementById('bp-title'), '#/benefit/' + id);
  const r = await page.evaluate(id => {
    const L = window.LANDIT, D = window.DUSK, b = L.benefitById(id);
    const panel = document.getElementById('bf-panel');
    const facts = {};
    panel.querySelectorAll('.fact').forEach(f => { facts[f.querySelector('dt').innerText.trim()] = f.querySelector('dd').innerText.trim(); });
    const worth = panel.querySelector('.bp-worth').innerText.trim();
    const banner = panel.querySelector('.banner') ? panel.querySelector('.banner').innerText.trim() : '';
    const region = panel.querySelector('.bp-region').innerText.trim();
    const sub = panel.querySelector('.bp-sub').innerText.trim();
    const rules = [...panel.querySelectorAll('#tp-overview .ticks li')].map(x => x.textContent.trim());
    const steps = [...panel.querySelectorAll('#tp-apply .steps li')].map(x => x.querySelector('.step-text').textContent.trim());
    const docs = [...panel.querySelectorAll('#tp-apply .checks li')].map(x => x.textContent.trim());
    const apply = panel.querySelector('#bp-apply') ? panel.querySelector('#bp-apply').getAttribute('href') : null;
    const sources = [...panel.querySelectorAll('.sources a')].map(a => a.getAttribute('href'));
    const all = panel.textContent;
    const disc = all.includes(L.disclaimer);
    const st = D.standing(b);
    return { b: { name: b.name, sub: b.sub, regionLabel: b.regionLabel, value: b.value, valueLabel: b.valueLabel, valueKind: b.valueKind, valueNote: b.valueNote, time: b.guide.time, decision: b.guide.decision, cost: b.guide.cost, rules: b.rules, steps: b.guide.steps, docs: b.docs.map(d => d.label), docsKnown: b.docsKnown, applyUrl: b.applyUrl, sources: b.sources, effortLabel: b.effortLabel, statRate: b.statRate, nrpf: b.nrpf, publicFunds: b.publicFunds, nrpfNote: b.nrpfNote, generic: b.guide.generic, about: b.about },
      facts, worth, banner, region, sub, rules, steps, docs, apply, sources, all, disc, st: st.state, money: L.formatMoney(b.value) };
  }, id);
  const p = [];
  const b = r.b;
  if (r.sub !== b.sub) p.push('sub differs');
  if (r.region !== b.regionLabel) p.push(`region "${r.region}" vs "${b.regionLabel}"`);
  if ((r.facts['To apply'] || '') !== (b.time || 'Not listed')) p.push(`time "${r.facts['To apply']}" vs "${b.time}"`);
  if ((r.facts['Decision'] || '') !== (b.decision || 'Not listed')) p.push(`decision "${r.facts['Decision']}" vs "${b.decision}"`);
  if ((r.facts['Cost'] || '') !== (b.cost || 'Not listed')) p.push(`cost "${r.facts['Cost']}" vs "${b.cost}"`);
  if (!r.facts['Effort'].startsWith(b.effortLabel || 'Not listed')) p.push(`effort "${r.facts['Effort']}" vs "${b.effortLabel}"`);
  if (b.statRate == null && !r.facts['Published approval rate'].includes('No published rate yet')) p.push('rate shown without data');
  if (b.statRate != null && !r.facts['Published approval rate'].startsWith(Math.round(b.statRate * 100) + '%')) p.push('rate mismatch');
  if (JSON.stringify(r.rules) !== JSON.stringify(b.rules)) p.push('rules differ ' + r.rules.length + ' vs ' + b.rules.length);
  if (JSON.stringify(r.steps) !== JSON.stringify(b.steps)) p.push('steps differ ' + r.steps.length + ' vs ' + b.steps.length);
  if (JSON.stringify(r.docs) !== JSON.stringify(b.docs)) p.push('docs differ');
  if (r.apply !== b.applyUrl) p.push('apply url differs ' + r.apply + ' vs ' + b.applyUrl);
  if (JSON.stringify(r.sources) !== JSON.stringify(b.sources)) p.push('sources differ');
  if (b.valueKind === 'amount' && !(r.worth.includes(r.money) && r.worth.includes(b.valueLabel))) p.push('amount/qualifier missing: ' + r.worth);
  if (b.valueKind === 'label' && !r.worth.includes(b.valueLabel)) p.push('label missing');
  if (b.nrpfNote && r.all.includes(b.nrpfNote.slice(0, 30))) p.push('nrpfNote LEAK');
  if (!r.disc) p.push('no disclaimer');
  const d = [...r.all.matchAll(DASHES)]; if (d.length) p.push('dash x' + d.length);
  const ban = findBanned(r.all); if (ban.length) p.push('banned: ' + ban.map(x => x.term).join(','));
  if (/\bNRPF\b|means-tested|Composition|disregarded|passport(ed)?\b|UC-gated|gated/.test(r.all)) p.push('jargon: ' + (r.all.match(/NRPF-safe|NRPF|means-tested|Composition-based|disregarded|UC-gated|gated/g) || []).join(','));
  if (p.length) problems.push({ id, st: r.st, p });
  samples[id] = { facts: r.facts, worth: r.worth, banner: r.banner, st: r.st };
}
fs.writeFileSync('/Users/armanbayatmaku/Desktop/landit-test/_review/b-dusk/review-brief/detail-audit.json', JSON.stringify({ problems, samples, errs }, null, 2));
console.log('checked', ids.length, 'errors', errs);
const tally = {};
problems.forEach(x => x.p.forEach(s => { const k = s.replace(/:.*/, '').replace(/".*/, ''); tally[k] = (tally[k] || 0) + 1; }));
console.log(tally);
problems.filter(x => x.p.some(s => !s.startsWith('jargon'))).forEach(x => console.log(x.id, x.st, x.p.join(' | ')));
await browser.close();
