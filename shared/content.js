  L.t = function (key, lang) {
    var s = L.i18n.strings;
    return (lang && s[lang] && s[lang][key]) || s.en[key] || key;
  };
  /* LANDIT.tf(key, vars, lang): same, with {name} placeholders filled. */
  L.tf = function (key, vars, lang) {
    var out = L.t(key, lang);
    Object.keys(vars || {}).forEach(function (k) { out = out.split('{' + k + '}').join(String(vars[k])); });
    return out;
  };
